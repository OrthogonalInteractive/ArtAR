export function artDimensions(art, unitsPerMeter = 1) {
  const border = 2 * (Number(art.frameCm) + Number(art.matCm))
  return {
    width: ((Number(art.widthCm) + border) / 100) * unitsPerMeter,
    height: ((Number(art.heightCm) + border) / 100) * unitsPerMeter,
    depth: (Number(art.depthCm) / 100) * unitsPerMeter,
  }
}
